"""Generate LaTeX table bodies from paper_results/tables/*.csv.

Every number in the thesis tables comes from these CSVs; nothing is typed by hand.
Run: python3 Tables/make_tables.py <path-to-paper_results/tables>
Writes Tables/*.tex next to this script.
"""
import csv
import os
import sys

SRC = sys.argv[1]
OUT = os.path.dirname(os.path.abspath(__file__))


def rows(name):
    with open(os.path.join(SRC, name), newline="", encoding="utf-8") as f:
        return list(csv.reader(f))


def dicts(name):
    with open(os.path.join(SRC, name), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def f2(x):
    return f"{float(x):.2f}".replace("-", "$-$")


def f1(x):
    return f"{float(x):.1f}".replace("-", "$-$")


def esc(s):
    return s.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def write(name, lines):
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        f.write("% Generated by make_tables.py from paper_results/tables. Do not edit by hand.\n")
        f.write("\n".join(lines) + "\n")


RUN_NAMES = {
    "lead-1": "Lead-1", "lead-2": "Lead-2", "lead-3": "Lead-3",
    "distilbert-squad": "DistilBERT-SQuAD",
    "flan-t5-small-zs-nr3": "Flan-T5-small 0-shot", "flan-t5-base-zs-nr3": "Flan-T5-base 0-shot",
    "qwen2.5-1.5b-instruct-zs-nr3": "Qwen2.5-1.5B 0-shot",
    "ft-flan-t5-small-s42-nr3": "Flan-T5-small FT (s42)",
    "ft-flan-t5-small-s42": "Flan-T5-small FT (s42), plain greedy",
    "ft-flan-t5-base-lora-s42-nr3": "Flan-T5-base LoRA FT",
    "ft-flan-t5-base-lora-s42": "Flan-T5-base LoRA FT, plain greedy",
}


def short(model):
    return (model.replace(" (0-shot)", " 0-shot").replace(" (QA)", "")
            .replace("Qwen2.5-1.5B-Instruct", "Qwen2.5-1.5B")
            .replace("(seed 42)", "(s42)").replace("(seed 43)", "(s43)").replace("(seed 44)", "(s44)"))


# Table: main results (means) and with CIs ---------------------------------
main = [r for r in dicts("main_results.csv") if r["main"] == "True"]
metrics = ["rouge1", "rouge2", "rougeL", "bleu", "token_f1", "bertscore_f1"]
best = {m: max(float(r[m]) for r in main) for m in metrics}
lines = []
prev_family = None
for r in main:
    if prev_family is not None and r["family"] != prev_family:
        lines.append(r"\midrule")
    prev_family = r["family"]
    cells = []
    for m in metrics:
        v = f2(r[m])
        cells.append(r"\textbf{" + v + "}" if float(r[m]) == best[m] else v)
    lines.append(esc(short(r["model"])) + " & " + " & ".join(cells) + r" \\")
write("main_results_body.tex", lines)

lines = []
prev_family = None
for r in main:
    if prev_family is not None and r["family"] != prev_family:
        lines.append(r"\midrule")
    prev_family = r["family"]
    cells = [f"{f2(r[m])} [{f2(r[m + '_lo'])}, {f2(r[m + '_hi'])}]" for m in ["rouge1", "rouge2", "rougeL"]]
    lines.append(esc(short(r["model"])) + " & " + " & ".join(cells) + r" \\")
write("main_results_ci_overlap_body.tex", lines)
lines = []
prev_family = None
for r in main:
    if prev_family is not None and r["family"] != prev_family:
        lines.append(r"\midrule")
    prev_family = r["family"]
    cells = [f"{f2(r[m])} [{f2(r[m + '_lo'])}, {f2(r[m + '_hi'])}]" for m in ["bleu", "token_f1", "bertscore_f1"]]
    lines.append(esc(short(r["model"])) + " & " + " & ".join(cells) + r" \\")
write("main_results_ci_other_body.tex", lines)

# Seed variance -------------------------------------------------------------
sv = {r[""]: r for r in dicts("seed_variance_ft_small.csv")}
cells = [f"{f2(sv['mean'][m])} $\\pm$ {f2(sv['std'][m])}" for m in metrics]
write("seed_variance_body.tex", ["Flan-T5-small FT (3 seeds) & " + " & ".join(cells) + r" \\"])

# Paired tests ----------------------------------------------------------------
pt = dicts("paired_tests.csv")
by = {}
for r in pt:
    by.setdefault((r["model_a"], r["model_b"]), {})[r["metric"]] = r


def pfmt(p):
    p = float(p)
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


lines = []
for (a, b), d in by.items():
    row = [esc(RUN_NAMES[a]) + " vs " + esc(RUN_NAMES[b])]
    for m in ["rougeL", "bertscore_f1"]:
        r = d[m]
        row.append(f"{f2(r['mean_diff'])} [{f2(r['ci_lo'])}, {f2(r['ci_hi'])}]")
        row.append(f1(r["a_wins_pct"]))
        row.append(pfmt(r["p_holm"]))
    lines.append(" & ".join(row) + r" \\")
write("paired_tests_body.tex", lines)

# Output properties -------------------------------------------------------------
op = dicts("output_properties.csv")
keep = ["Human reference", "Source context", "Lead-3", "DistilBERT-SQuAD (QA)", "Flan-T5-small (0-shot)",
        "Flan-T5-base (0-shot)", "Qwen2.5-1.5B-Instruct (0-shot)", "Flan-T5-small FT (seed 42)",
        "Flan-T5-base LoRA FT (seed 42)"]
opd = {r["run"]: r for r in op}
lines = []
for k in keep:
    r = opd[k]
    def g(c, fmt):
        return fmt(r[c]) if r[c] != "" else "--"
    lines.append(" & ".join([esc(short(k)), g("n_words", f1), g("fkgl", f2), g("flesch", f1),
                             g("novel_bigram", f2), g("num_support", f2), g("code_support", f2),
                             g("empty_rate", f1)]) + r" \\")
    if k == "Source context":
        lines.append(r"\midrule")
write("output_properties_body.tex", lines)

# Decoding ablation -------------------------------------------------------------
da = rows("decoding_ablation.csv")
header, sub = da[0], da[1]
cols = {(header[i], sub[i]): i for i in range(1, len(header))}
lines = []
for r in da[3:]:
    def v(metric, mode, fmt):
        return fmt(r[cols[(metric, mode)]])
    PG, NR = "plain greedy", "greedy, no-repeat-3"
    lines.append(" & ".join([
        esc(short(r[0])),
        v("rougeL", PG, f2), v("rougeL", NR, f2),
        v("bertscore_f1", PG, f2), v("bertscore_f1", NR, f2),
        v("repetitive_pct", PG, f2), v("repetitive_pct", NR, f2),
        v("code_support", PG, f2), v("code_support", NR, f2),
        v("num_support", PG, f2), v("num_support", NR, f2),
    ]) + r" \\")
write("decoding_ablation_body.tex", lines)

# Dataset tables -------------------------------------------------------------------
lines = []
for r in dicts("dataset_question_coverage.csv"):
    lines.append(" & ".join([esc(r["question"]), r["usable"], r["no answer"], r["no context"],
                             esc(r["mapped report sections"])]) + r" \\")
write("dataset_coverage_body.tex", lines)

lines = []
sp = dicts("dataset_splits.csv")
for r in sp:
    lines.append(f"{r[''].capitalize()} & {r['trials']} & {r['examples']}" + r" \\")
lines.append(r"\midrule")
lines.append(f"Total & {sum(int(r['trials']) for r in sp)} & {sum(int(r['examples']) for r in sp)}" + r" \\")
write("dataset_splits_body.tex", lines)

lines = []
for r in dicts("dataset_splits_per_question.csv"):
    lines.append(f"{esc(r['row_0'])} & {r['train']} & {r['val']} & {r['test']}" + r" \\")
write("dataset_splits_per_question_body.tex", lines)

ts = {r[""]: r for r in dicts("dataset_text_statistics.csv")}
labels = [("context_words", "Report context: words"), ("reference_words", "Reference: words"),
          ("context_fkgl", "Report context: FKGL"), ("reference_fkgl", "Reference: FKGL"),
          ("context_fre", "Report context: Flesch Reading Ease"),
          ("reference_fre", "Reference: Flesch Reading Ease"),
          ("novel_bigrams", "Reference bigrams absent from context (share)")]
lines = [f"{lab} & {f2(ts[k]['mean'])} & {f2(ts[k]['50%'])} & {f2(ts[k]['std'])}" + r" \\" for k, lab in labels]
write("dataset_text_stats_body.tex", lines)

# Per-question ROUGE-L ---------------------------------------------------------------
pq = rows("per_question_rougeL_wide.csv")
lines = [" & ".join([esc(short(r[0]))] + [f1(x) for x in r[1:]]) + r" \\" for r in pq[1:]]
write("per_question_body.tex", lines)
write("per_question_head.tex", [" & ".join(["System"] + [esc(h) for h in pq[0][1:]]) + r" \\"])

# Compute cost -------------------------------------------------------------------------
lines = []
for r in dicts("compute_cost.csv"):
    lat = float(r["median_latency_s"])
    latf = "$<$0.01" if lat < 0.01 else f"{lat:.2f}"
    tm = f1(r["train_minutes"]) if r["train_minutes"] else "--"
    ep = str(int(float(r["epochs_run"]))) if r["epochs_run"] else "--"
    lines.append(" & ".join([esc(short(r["model"])), latf, tm, ep]) + r" \\")
write("compute_cost_body.tex", lines)

# RAG retrieval ------------------------------------------------------------------------
lines = [f"{r['k']} & {float(r['recall@k']):.3f} & {float(r['precision@k']):.3f} & {float(r['mrr']):.3f}" + r" \\"
         for r in dicts("rag_retrieval.csv")]
write("rag_body.tex", lines)
print("ok")
